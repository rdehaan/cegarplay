// Copy the clingo-wasm engine from test/node_modules into vendor/clingo-wasm/.
//   node tools/vendor.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const pkgDir = path.join(root, 'test', 'node_modules', 'clingo-wasm');
const src = path.join(pkgDir, 'dist');
const dst = path.join(root, 'vendor', 'clingo-wasm');
const files = ['clingo.js', 'clingo.wasm', 'clingo-mt.js', 'clingo-mt.wasm'];

if (!fs.existsSync(src)) {
  console.error(`missing ${src}: run "cd test && npm install" first`);
  process.exit(1);
}
const version = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
fs.mkdirSync(dst, { recursive: true });
const lines = [`clingo-wasm ${version}`];
for (const f of files) {
  const data = fs.readFileSync(path.join(src, f));
  fs.writeFileSync(path.join(dst, f), data);
  lines.push(`${crypto.createHash('sha256').update(data).digest('hex')}  ${f}`);
}
fs.writeFileSync(path.join(dst, 'package.json'), '{ "type": "module" }\n');
fs.writeFileSync(path.join(dst, 'VERSION'), lines.join('\n') + '\n');
console.log(lines.join('\n'));

// Fonts: Open Sans (400, 600, 700, latin + latin-ext) and Font Awesome (v4 names).
const nm = path.join(root, 'test', 'node_modules');
const fontDir = path.join(root, 'vendor', 'fonts');
fs.mkdirSync(fontDir, { recursive: true });
const os = path.join(nm, '@fontsource', 'open-sans');
const fa = path.join(nm, '@fortawesome', 'fontawesome-free');
const css = ['/* Generated by tools/vendor.mjs. Open Sans (SIL OFL 1.1) and Font Awesome Free (fonts SIL OFL 1.1, icons CC BY 4.0). */'];
const latinRange = 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';
for (const w of [400, 600, 700]) {
  const f = `open-sans-latin-${w}-normal.woff2`;
  fs.copyFileSync(path.join(os, 'files', f), path.join(fontDir, f));
  css.push(`@font-face {\n  font-family: 'Open Sans';\n  font-style: normal;\n  font-display: swap;\n  font-weight: ${w};\n  src: url('${f}') format('woff2');\n  unicode-range: ${latinRange};\n}`);
}
// Only the faces the page uses: the icons (tabs, info links) are solid glyphs, and the bar chart
// (U+F080) comes from the v4 compatibility face. The brands face has no unicode-range, so the
// browser would download it (115 KB) for every icon; the regular face covers none of the icons.
const FA_DROP = ['fa-brands-400.woff2', 'fa-regular-400.woff2'];
const faCss = fs.readFileSync(path.join(fa, 'css', 'v4-font-face.css'), 'utf8')
  .replace(/@font-face\s*{[^}]*}/g, (block) => (FA_DROP.some((f) => block.includes(f)) ? '' : block))
  .replace(/\n{3,}/g, '\n');
for (const f of FA_DROP) fs.rmSync(path.join(fontDir, f), { force: true });
for (const m of faCss.matchAll(/url\("\.\.\/webfonts\/([^"]+)"\)/g)) fs.copyFileSync(path.join(fa, 'webfonts', m[1]), path.join(fontDir, m[1]));
css.push(faCss.replace(/\/\*![\s\S]*?\*\/\s*/, '').replace(/\.\.\/webfonts\//g, '').trim());
fs.writeFileSync(path.join(fontDir, 'fonts.css'), css.join('\n') + '\n');
fs.copyFileSync(path.join(os, 'LICENSE'), path.join(fontDir, 'LICENSE-open-sans.txt'));
fs.copyFileSync(path.join(fa, 'LICENSE.txt'), path.join(fontDir, 'LICENSE-font-awesome.txt'));
console.log('fonts: ' + fs.readdirSync(fontDir).join(' '));

// coi-serviceworker (MIT): adds the cross-origin isolation headers on hosts that cannot send them.
const coi = path.join(nm, 'coi-serviceworker');
if (fs.existsSync(coi)) {
  fs.copyFileSync(path.join(coi, 'coi-serviceworker.js'), path.join(root, 'coi-serviceworker.js'));
  const v = JSON.parse(fs.readFileSync(path.join(coi, 'package.json'), 'utf8')).version;
  console.log(`coi-serviceworker ${v}`);
}
